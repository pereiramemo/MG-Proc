"""Shared helpers for the MG-Proc bin/ Python scripts.

Provides the standard logging helpers and the standardized log-file builder
described in the project CLAUDE.md, plus sequence-statistic helpers (read
counts and mean lengths) used by the preprocessing and assembly scripts.
Because the bin/ scripts run standalone (invoked by name from PATH, e.g. under
Nextflow), import this module by adding the script's own directory to sys.path
first:

    import os, sys
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from toolbox import log, log_warn, log_error, derive_sample_name, build_log

The log/log_warn/log_error helpers print to the console and also accumulate
ANSI-free messages that build_log() emits in the Info/Warnings/Errors sections
of the general-info block.
"""

import bz2
import gzip
import re
import sys
from datetime import datetime
from pathlib import Path

# ── Run state (per process) ──────────────────────────────────────────────────
_info = []
_warnings = []
_errors = []

_ANSI_RE = re.compile(r'\033\[[0-9;]*m')


def _clean(msg):
    """Strip ANSI color codes so the log file stays plain text."""
    return _ANSI_RE.sub('', str(msg))


def log(msg):
    """Log an informational message to stdout and the Info section."""
    print(f"[INFO] {msg}")
    _info.append(_clean(msg))


def log_warn(msg):
    """Log a warning to stderr and the Warnings section."""
    print(f"\033[1;33m[WARN]\033[0m {msg}", file=sys.stderr)
    _warnings.append(_clean(msg))


def log_error(msg):
    """Log an error to stderr and the Errors section."""
    print(f"\033[0;31m[ERROR]\033[0m {msg}", file=sys.stderr)
    _errors.append(_clean(msg))


def derive_sample_name(reads1, strip_read_suffix=False, sanitize=False):
    """Derive a sample name from an R1 filename.
    strip_read_suffix: drop a trailing _R1/-R1 (and anything after it).
    sanitize:          replace '-' with '_'.
    """
    name = Path(reads1).name
    for ext in (".fastq.gz", ".fq.gz", ".fastq", ".fq", ".fasta.gz", ".fa.gz",
                ".fasta", ".fa"):
        if name.endswith(ext):
            name = name[: -len(ext)]
            break
    if strip_read_suffix:
        stripped = re.sub(r'[_\-][Rr]1(?:[_\-].*)?$', '', name)
        name = stripped if stripped else name
    if sanitize:
        name = name.replace("-", "_")
    return name


def _section(title, items):
    if items:
        return [f"{title}:"] + [f"    {x}" for x in items]
    return [f"{title}:", "    None"]


def build_log(script_name, script_desc, sample_name, inputs, params,
              outputs, command, exit_status, tool_log=""):
    """Assemble the standardized log file following the project CLAUDE.md.
    The general-info block (script name, description, date, sample, inputs,
    parameters, outputs, command, captured Info/Warnings/Errors and exit
    status) must not contain any data statistics; those live in stats/.
    The third-party tool output, if any, is appended in its own section.
    """
    sep = "=" * 80
    lines = [
        sep, "Start of general log info", sep,
        "",
        "Script name:",
        f"    {script_name}",
        "",
        "Script description:",
        f"    {script_desc}",
        "",
        "Date:",
        f"    {datetime.now()}",
        "",
        "Sample name:",
        f"    {sample_name}",
        "",
        "Input data:",
    ]
    lines += [f"    {x}" for x in inputs] + [""]
    lines.append("Parameters:")
    lines += [f"    {x}" for x in params] + [""]
    lines.append("Output data:")
    lines += [f"    {x}" for x in outputs] + [""]
    lines += ["- Command executed:", f"    {command}", ""]
    lines += _section("Info", _info) + [""]
    lines += _section("Warnings", _warnings) + [""]
    lines += _section("Errors", _errors) + [""]
    lines += [f"Exit status: {exit_status}", "",
              sep, "End of general log info.", sep] + [""]
    if tool_log:
        lines += [sep, "Log info generated by third-party tools.", sep]
        lines.append(tool_log.rstrip("\n"))
    return "\n".join(lines) + "\n"


# ── Sequence statistics ──────────────────────────────────────────────────────
# These replace the conf.sh helpers (count_fastq via `wc -l`, count_fasta via
# `egrep -c`, compute_mean_length via emboss `infoseq`). Working in Python keeps
# the preprocessing image free of emboss and avoids the `wc -l | cut` parsing
# bug and gawk-only `gensub` in the old stats block.

def _magic(path):
    """Return the first two bytes of a file (for compression detection)."""
    with open(path, "rb") as fh:
        return fh.read(2)


def open_maybe_compressed(path, mode="rt"):
    """Open a plain, gzip, or bzip2 file transparently (detected by magic bytes)."""
    sig = _magic(path)
    if sig == b"\x1f\x8b":
        return gzip.open(path, mode)
    if sig == b"BZ":
        return bz2.open(path, mode)
    return open(path, mode)


def count_fastq(path):
    """Number of reads in a FASTQ file (4 lines per record)."""
    n = 0
    with open_maybe_compressed(path) as fh:
        for n, _ in enumerate(fh, start=1):
            pass
    return n // 4


def count_fasta(path):
    """Number of sequences in a FASTA file (header lines starting with '>')."""
    n = 0
    with open_maybe_compressed(path) as fh:
        for line in fh:
            if line.startswith(">"):
                n += 1
    return n


def mean_length(path, fmt="fastq"):
    """Mean sequence length in a FASTA or FASTQ file (0 when empty)."""
    total = 0
    count = 0
    with open_maybe_compressed(path) as fh:
        if fmt == "fastq":
            for i, line in enumerate(fh):
                if i % 4 == 1:  # sequence line
                    total += len(line.rstrip("\n"))
                    count += 1
        else:  # fasta
            seq_len = 0
            started = False
            for line in fh:
                if line.startswith(">"):
                    if started:
                        total += seq_len
                        count += 1
                    seq_len = 0
                    started = True
                else:
                    seq_len += len(line.rstrip("\n"))
            if started:
                total += seq_len
                count += 1
    return total / count if count else 0
